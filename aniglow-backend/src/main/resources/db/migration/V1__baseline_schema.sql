CREATE TABLE IF NOT EXISTS agent_votes (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    candidate_id BIGINT NOT NULL,
    week_key VARCHAR(10),
    created_at DATETIME DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uk_user_week (user_id, week_key),
    KEY idx_agent_vote_candidate (candidate_id),
    CONSTRAINT fk_agent_vote_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_agent_vote_candidate FOREIGN KEY (candidate_id) REFERENCES agent_vote_candidates (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS ratings (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    anime_id BIGINT NOT NULL,
    score DECIMAL(3,1) NOT NULL,
    review VARCHAR(1000),
    story_score DECIMAL(3,1),
    animation_score DECIMAL(3,1),
    sound_score DECIMAL(3,1),
    character_score DECIMAL(3,1),
    enjoyment_score DECIMAL(3,1),
    is_recommended BIT(1),
    contains_spoiler BIT(1),
    like_count BIGINT,
    created_at DATETIME(6),
    updated_at DATETIME(6),
    PRIMARY KEY (id),
    UNIQUE KEY uk_user_anime_rating (user_id, anime_id),
    KEY idx_anime_rating (anime_id, score DESC),
    KEY idx_user_rating (user_id, created_at DESC),
    KEY idx_created_at (created_at),
    CONSTRAINT fk_ratings_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_ratings_anime FOREIGN KEY (anime_id) REFERENCES anime (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS rating_replies (
    id BIGINT NOT NULL AUTO_INCREMENT,
    rating_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    content VARCHAR(800) NOT NULL,
    like_count BIGINT,
    created_at DATETIME(6),
    updated_at DATETIME(6),
    PRIMARY KEY (id),
    KEY idx_rating_reply (rating_id, created_at),
    KEY idx_reply_user (user_id, created_at),
    CONSTRAINT fk_rating_replies_rating FOREIGN KEY (rating_id) REFERENCES ratings (id),
    CONSTRAINT fk_rating_replies_user FOREIGN KEY (user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS communities (
    id BIGINT NOT NULL AUTO_INCREMENT,
    slug VARCHAR(80) NOT NULL,
    name VARCHAR(80) NOT NULL,
    description VARCHAR(500),
    cover_image VARCHAR(500),
    category VARCHAR(50),
    tags VARCHAR(500),
    related_anime_id BIGINT,
    post_count BIGINT NOT NULL,
    member_count BIGINT NOT NULL,
    heat_score BIGINT NOT NULL,
    is_featured BIT(1) NOT NULL,
    creator_id BIGINT,
    created_at DATETIME(6),
    updated_at DATETIME(6),
    PRIMARY KEY (id),
    UNIQUE KEY idx_community_slug (slug),
    KEY idx_community_category (category),
    KEY idx_community_heat (heat_score DESC),
    KEY idx_community_anime (related_anime_id),
    CONSTRAINT fk_community_anime FOREIGN KEY (related_anime_id) REFERENCES anime (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS community_posts (
    id BIGINT NOT NULL AUTO_INCREMENT,
    community_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    title VARCHAR(120) NOT NULL,
    content TEXT NOT NULL,
    cover_image VARCHAR(500),
    images TEXT,
    like_count BIGINT NOT NULL,
    reply_count BIGINT NOT NULL,
    view_count BIGINT NOT NULL,
    is_pinned BIT(1) NOT NULL,
    is_featured BIT(1) NOT NULL,
    is_deleted BIT(1) NOT NULL,
    last_replied_at DATETIME(6),
    created_at DATETIME(6),
    updated_at DATETIME(6),
    PRIMARY KEY (id),
    KEY idx_post_community_reply (community_id, last_replied_at),
    KEY idx_post_community_created (community_id, created_at),
    KEY idx_post_author (user_id, created_at),
    CONSTRAINT fk_community_posts_community FOREIGN KEY (community_id) REFERENCES communities (id),
    CONSTRAINT fk_community_posts_user FOREIGN KEY (user_id) REFERENCES users (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS community_replies (
    id BIGINT NOT NULL AUTO_INCREMENT,
    post_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    content VARCHAR(1200) NOT NULL,
    like_count BIGINT NOT NULL,
