CREATE TABLE IF NOT EXISTS users (
    id BIGINT NOT NULL AUTO_INCREMENT,
    username VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    password VARCHAR(255) NOT NULL,
    phone VARCHAR(20),
    display_name VARCHAR(80),
    avatar_url MEDIUMTEXT,
    role ENUM('USER', 'ADMIN', 'MODERATOR') NOT NULL,
    is_active BIT(1),
    created_at DATETIME(6),
    updated_at DATETIME(6),
    last_login_at DATETIME(6),
    authing_id VARCHAR(100),
    PRIMARY KEY (id),
    UNIQUE KEY uk_users_username (username),
    UNIQUE KEY uk_users_email (email),
    UNIQUE KEY uk_users_phone (phone),
    UNIQUE KEY uk_users_authing_id (authing_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS anime (
    id BIGINT NOT NULL AUTO_INCREMENT,
    mal_id BIGINT,
    title VARCHAR(200) NOT NULL,
    title_japanese VARCHAR(200),
    title_english VARCHAR(200),
    title_cn VARCHAR(200),
    search_aliases VARCHAR(1200),
    synopsis VARCHAR(2000),
    synopsis_cn VARCHAR(2000),
    cover_image VARCHAR(500),
    trailer_url VARCHAR(500),
    type VARCHAR(50),
    status VARCHAR(100),
    aired_from DATE,
    aired_to DATE,
    episodes INT,
    duration_minutes INT,
    rating VARCHAR(50),
    popularity BIGINT,
    members_count BIGINT,
    favorites_count BIGINT,
    has_agent TINYINT(1) NOT NULL DEFAULT 0,
    bayesian_rating DECIMAL(4,2),
    mean_rating DECIMAL(4,2),
    rating_count BIGINT,
    community_bayesian_rating DECIMAL(4,2),
    community_mean_rating DECIMAL(4,2),
    community_rating_count BIGINT NOT NULL DEFAULT 0,
    firefly_vote_count BIGINT NOT NULL DEFAULT 0,
    studio VARCHAR(100),
    source VARCHAR(50),
    season VARCHAR(20),
    year INT,
    created_at DATETIME(6),
    updated_at DATETIME(6),
    synced_at DATETIME(6),
    PRIMARY KEY (id),
    UNIQUE KEY idx_mal_id (mal_id),
    KEY idx_rating (bayesian_rating DESC),
    KEY idx_popularity (popularity),
    KEY idx_has_agent (has_agent),
    KEY idx_title_cn (title_cn),
    KEY idx_community_rating (community_bayesian_rating DESC),
    KEY idx_firefly_votes (firefly_vote_count DESC),
    KEY idx_anime_year_season (year, season),
    KEY idx_anime_status (status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS anime_genres (
    anime_id BIGINT NOT NULL,
    genre VARCHAR(255),
    KEY idx_anime_genres_anime (anime_id),
    CONSTRAINT fk_anime_genres_anime FOREIGN KEY (anime_id) REFERENCES anime (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

