) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS firefly_votes (
    id BIGINT NOT NULL AUTO_INCREMENT,
    user_id BIGINT NOT NULL,
    anime_id BIGINT NOT NULL,
    created_at DATETIME(6),
    PRIMARY KEY (id),
    KEY idx_firefly_vote_anime (anime_id, created_at),
    KEY idx_firefly_vote_user (user_id, created_at),
    CONSTRAINT fk_firefly_votes_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT fk_firefly_votes_anime FOREIGN KEY (anime_id) REFERENCES anime (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
